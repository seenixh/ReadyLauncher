    // The letters in upper and lower case, for strips 7 to 10 lamps high. Some of the rows can be kept below the line for
    // the tails of g, j, p, q and y; the capitals get the rest. There's a set of letters for each height of capitals
    // (5 to 10), and the letters with tails are put together for the room they have.
    internal partial class LampFont
    {
        public const int MinRows = 6, MaxRows = 10, MaxTailRows = 4;
        const int LowestCapitals = 5;
        static readonly Dictionary<int, LampFont> made = new Dictionary<int, LampFont>();

        /// <summary>How many of a strip's rows can be kept for tails: none at six (its text is capitals); capitals stay at least five high.</summary>
        public static int TailRowsFor(int rows) { return rows <= MinRows ? 0 : Math.Min(MaxTailRows, rows - LowestCapitals); }

        /// <summary>
        /// The letters for a strip this many lamps high: capitals only at six (or less), upper and lower case above that,
        /// with this many of the rows kept below the line for tails (as many as there can be).
        /// </summary>
        public static LampFont For(int rows, int tails)
        {
            if (rows <= MinRows) return Capitals;
            rows = Math.Min(MaxRows, rows);
            tails = Math.Max(0, Math.Min(TailRowsFor(rows), tails));
            LampFont font;
            int key = rows * 10 + tails;
            if (!made.TryGetValue(key, out font)) made[key] = font = Make(rows, tails);
            return font;
        }

        static LampFont Make(int rows, int tails)
        {
            int capitals = rows - tails, line = capitals - 1;   // the line: the row the letters sit on
            var glyphs = new Dictionary<char, string[]>();
            foreach (var text in Letters(capitals).Split('\n'))   // the letter, the row its top is on, then its rows
            {
                var parts = text.Split(new[] { ' ', '\r' }, StringSplitOptions.RemoveEmptyEntries);
                if (parts.Length < 3) continue;
                var lamps = new List<string>(parts);
                lamps.RemoveRange(0, 2);
                Put(glyphs, rows, parts[0][0], int.Parse(parts[1], CultureInfo.InvariantCulture), lamps);
            }

            // Letters with tails. With no room below the line, the tail takes the letter's own lowest two rows; with one
            // row, g and y start theirs a row above the line. Three or more: the tails of g and y curl.
            int x = SmallHeight(capitals), top = capitals - x;
            bool wide = x > 4, big = capitals >= 7;
            string side = wide ? "#...#" : "#..#", bar = wide ? ".####" : ".###", barP = wide ? "####." : "###.";
            string right = wide ? "....#" : "...#", left = wide ? "#...." : "#...", hook = wide ? ".###." : "###.", curl = wide ? ".###." : ".##.";
            int inside = tails == 0 ? 2 : tails == 1 ? 1 : 0, tail = inside + tails, bowl = x - inside;
            var hang = tail >= 3 ? Times(right, tail - 2, side, curl) : Times(right, tail - 1, hook);
            var g = new List<string> { bar };
            g.AddRange(Times(side, bowl - 2, bar));
            g.AddRange(hang);
            Put(glyphs, rows, 'g', top, g);
            var y = Times(side, bowl - 1, bar);
            y.AddRange(hang);
            Put(glyphs, rows, 'y', top, y);
            int stem = tails == 0 ? 2 : tails, loop = tails == 0 ? x - 2 : x;
            var p = new List<string> { barP };
            p.AddRange(Times(side, loop - 2, barP));
            p.AddRange(Times(left, stem));
            Put(glyphs, rows, 'p', top, p);
            var q = new List<string> { bar };
            q.AddRange(Times(side, loop - 2, bar));
            q.AddRange(Times(right, stem));
            Put(glyphs, rows, 'q', top, q);
            int dot = top >= 3 ? 1 : 0, start = Math.Max(top, dot + 2);
            var j = new List<string> { "..#" };
            j.AddRange(Times("...", start - dot - 1));
            if (tails == 2) { j.Add(".##"); j.AddRange(Times("..#", line + tails - 1 - start, "##.")); }
            else j.AddRange(Times("..#", line + tails - 1 - start, "#.#", ".#."));
            Put(glyphs, rows, 'j', dot, j);

            // Marks that hang below the line when there's room.
            var comma = big ? new List<string> { "##", "##" } : new List<string> { ".#" };
            if (tails != 1) comma.Add(".#");
            comma.Add("#.");
            int commaTop = !big ? line : tails == 0 ? line - 3 : line - 1;
            Put(glyphs, rows, ',', commaTop, comma);
            var semicolon = big ? new List<string> { "##", "##" } : new List<string> { ".#" };
            int upper = big && tails == 0 ? line - 6 : top;
            semicolon.AddRange(Times("..", commaTop - upper - semicolon.Count));
            semicolon.AddRange(comma);
            Put(glyphs, rows, ';', upper, semicolon);
            Put(glyphs, rows, '_', tails == 0 ? line : line + 1, new List<string> { big ? "#####" : "####" });

            return new LampFont(rows, big ? 4 : 3, true, glyphs);
        }

        /// <summary>A row so many times, then some more rows.</summary>
        static List<string> Times(string row, int count, params string[] then)
        {
            var rows = new List<string>();
            for (int k = 0; k < count; k++) rows.Add(row);
            rows.AddRange(then);
            return rows;
        }

        /// <summary>Adds a letter, with empty rows above and below it.</summary>
        static void Put(Dictionary<char, string[]> glyphs, int height, char c, int top, List<string> lamps)
        {
            string blank = new string('.', lamps[0].Length);
            var rows = new string[height];
            for (int r = 0; r < height; r++) rows[r] = r >= top && r - top < lamps.Count ? lamps[r - top] : blank;
            glyphs[c] = rows;
        }

        /// <summary>How high small letters are, with capitals this high.</summary>
        static int SmallHeight(int capitals)
        {
            switch (capitals)
            {
                case 5: case 6: return 4;
                case 7: return 5;
                case 8: case 9: return 6;
                default: return 7;
            }
        }

        /// <summary>The letters (all but the ones with tails and the marks that hang) for capitals this high.</summary>
        static string Letters(int capitals)
        {
            switch (capitals)
            {
                case 5: return Five;
                case 6: return Six;
                case 7: return Seven;
                case 8: return Eight;
                case 9: return Nine;
                default: return Ten;
            }
        }

